export const catalogBarcodes: Record<string, BarcodeEntry> = Object.fromEntries(
  Object.entries(codes).flatMap(([code, name]) => {
    const company = catalogCompanies.find((item) => item.name === name);
    if (!company) throw new Error(`Missing company ${name}`);
    const entry: BarcodeEntry = {
      company: company.name,
      status: company.status,
      reason: company.reason,
    };
    const keys = code.length === 12 ? [code, `0${code}`] : [code];
    return keys.map((key) => [key, entry]);
  }),
);
